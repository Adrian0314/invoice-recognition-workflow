# -*- coding: utf-8 -*-
"""
发票代码 / 发票号码的规范编码规则
==================================
集中实现两份官方编码规则，供各样本生成器复用，避免同一套规则在多处各写一遍。

规则一：12 位「发票代码」（增值税电子普通发票 / 增值税电子专用发票）
--------------------------------------------------------------------
    第 1    位    固定为 0
    第 2 -  5位    省、自治区、直辖市和计划单列市代码（4 位）
    第 6 -  7位    年度（公历年后两位）
    第 8 - 10位    印制批次（3 位）
    第 11- 12位    票种：11 = 增值税电子普通发票，13 = 增值税电子专用发票
依据：国家税务总局公告 2020 年第 22 号（电子专票代码第 11-12 位为 13）；
      国家税务总局公告 2017 年第 44 号（普通发票代码统一为 12 位）。

规则二：20 位「数电（全电）发票号码」
--------------------------------------------------------------------
    第 1 -  2位    开票年份后两位
    第 3 -  4位    开票方所在省级税务局区域代码（省级行政区划代码前两位）
    第 5    位    开具渠道：1-6 为电子发票服务平台在线分配，0 暂不使用，7-9 保留
    第 6 - 20位    15 位顺序编码
依据：国家税务总局公告 2024 年第 11 号。

规则三：8 位「发票号码」（老版增值税电子普通发票 / 电子专用发票）
--------------------------------------------------------------------
    按年度、分批次编制，由税务机关在 12 位代码的批次内分配。

关于地区代码
------------
第 2-5 位用全国行政区划代码的地市级 4 位码；直辖市用「省级码 + 00」，
如北京 1100、上海 3100、重庆 5000；计划单列市用自身地市码，如深圳 4403、
厦门 3502；台湾省用 7100。
"""
from __future__ import annotations

# 省 / 自治区 / 直辖市 / 计划单列市 —— 发票代码第 2-5 位用的 4 位地区码
REGION4 = {
    "北京": "1100", "天津": "1200", "上海": "3100", "重庆": "5000",
    "河北": "1300", "山西": "1400", "辽宁": "2100", "吉林": "2200",
    "黑龙江": "2300", "江苏": "3200", "浙江": "3300", "安徽": "3400",
    "福建": "3500", "江西": "3600", "山东": "3700", "河南": "4100",
    "湖北": "4200", "湖南": "4300", "广东": "4400", "广西": "4500",
    "海南": "4600", "四川": "5100", "贵州": "5200", "云南": "5300",
    "西藏": "5400", "陕西": "6100", "甘肃": "6200", "青海": "6300",
    "宁夏": "6400", "新疆": "6500", "台湾": "7100",
    # 计划单列市（发票代码中单独占一个地区码）
    "大连": "2102", "宁波": "3302", "厦门": "3502", "青岛": "3702", "深圳": "4403",
    # 常用地市
    "广州": "4401", "杭州": "3301", "南京": "3201", "苏州": "3205",
    "武汉": "4201", "成都": "5101", "西安": "6101", "长沙": "4301",
    "郑州": "4101", "济南": "3701", "青岛黄岛": "3702",
}

# 发票代码第 11-12 位：票种
KIND_CODE = {"普票": "11", "专票": "13"}


def region4(name: str) -> str:
    """取 4 位地区码；未知地区抛错，避免悄悄生成一个假地区。"""
    if name not in REGION4:
        raise KeyError(f"未收录的地区：{name}，请在 REGION4 中补充")
    return REGION4[name]


def invoice_code(region: str, year: int, batch: int, kind: str = "普票") -> str:
    """
    生成 12 位发票代码。

    region 可以是 4 位地区码（"3100"）或地区名（"上海"）；
    batch 为 3 位印制批次（1 → "001"）。
    """
    r4 = REGION4[region] if region in REGION4 else region
    if len(r4) != 4 or not r4.isdigit():
        raise ValueError(f"地区码必须是 4 位数字，收到 {r4!r}")
    if kind not in KIND_CODE:
        raise ValueError(f"票种只能是 {list(KIND_CODE)}，收到 {kind!r}")
    if not 1 <= batch <= 999:
        raise ValueError(f"批次需在 1-999 之间，收到 {batch}")
    return f"0{r4}{year % 100:02d}{batch:03d}{KIND_CODE[kind]}"


def e_invoice_no(region: str, year: int, seq: int, channel: int = 1) -> str:
    """
    生成 20 位数电发票号码。

    region 取省级前两位（"31"）或地区名（"上海" → 3100 → 31）；
    channel 为开具渠道，1-6 为在线分配（默认 1）。
    """
    r4 = REGION4[region] if region in REGION4 else region
    prov = r4[:2]
    if not prov.isdigit():
        raise ValueError(f"无法从 {region!r} 解析省级代码")
    if not 0 <= channel <= 9:
        raise ValueError("开具渠道应为 0-9 的一位数字")
    if not 0 <= seq < 10 ** 15:
        raise ValueError("顺序编码超出 15 位上限")
    return f"{year % 100:02d}{prov}{channel}{seq:015d}"


def check(*pairs: tuple[str, str]) -> list[str]:
    """自检：校验生成结果的位数与结构，返回问题列表（空表示全部通过）。"""
    bad: list[str] = []
    for label, val in pairs:
        if len(val) != 12:
            bad.append(f"{label} 发票代码应为 12 位，实际 {len(val)} 位：{val}")
        elif val[0] != "0" or not val.isdigit():
            bad.append(f"{label} 发票代码首位应为 0 且全为数字：{val}")
        elif val[10:] not in KIND_CODE.values():
            bad.append(f"{label} 发票代码票种位应为 11/13，实际 {val[10:]}：{val}")
    return bad


if __name__ == "__main__":
    print("—— 规则自检 ——")
    demo = [
        ("上海 电子普票 2026 批次1", invoice_code("上海", 2026, 1)),
        ("上海 电子专票 2026 批次5", invoice_code("上海", 2026, 5, "专票")),
        ("深圳 电子普票 2026 批次2", invoice_code("深圳", 2026, 2)),
        ("台湾 电子普票 2026 批次1", invoice_code("台湾", 2026, 1)),
    ]
    for label, val in demo:
        print(f"  {label:<24} {val}   （{len(val)} 位）")

    print("\n—— 20 位号码 ——")
    for label, val in [
        ("上海 2026 第 1 号", e_invoice_no("上海", 2026, 1)),
        ("台湾 2026 第 12 号", e_invoice_no("台湾", 2026, 12)),
        ("深圳 2026 第 3 号", e_invoice_no("深圳", 2026, 3)),
    ]:
        print(f"  {label:<20} {val}   （{len(val)} 位）")

    problems = check(*(p for p in demo))
    print("\n自检结果：", "全部通过" if not problems else problems)
